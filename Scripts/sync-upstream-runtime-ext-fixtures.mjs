#!/usr/bin/env node
// Generates Tests/OpenClawLinuxRuntimeTests/UpstreamRuntimeExtFixtures.swift from the pinned
// upstream OpenClaw checkout (no network). Fixtures are emitted as Swift source so the test target
// needs no resource declarations.
//
// Covered: plugin hook names (src/plugins/hook-types.ts PLUGIN_HOOK_NAMES), the SKILL.md frontmatter
// corpus (skills/*/SKILL.md and custodian-skills/*/SKILL.md: frontmatter plus the body up to the
// first H1), and the upstream tag/commit the fixtures came from.
//
// Usage:
//   node Scripts/sync-upstream-runtime-ext-fixtures.mjs          # write the fixture file
//   node Scripts/sync-upstream-runtime-ext-fixtures.mjs --check  # fail when the file is stale
// Environment: OPENCLAW_UPSTREAM_DIR (default: .codex/openclaw next to this repo).

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.resolve(process.env.OPENCLAW_UPSTREAM_DIR ?? path.join(repoRoot, ".codex", "openclaw"));
const outputPath = path.join(repoRoot, "Tests", "OpenClawLinuxRuntimeTests", "UpstreamRuntimeExtFixtures.swift");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`sync-upstream-runtime-ext-fixtures: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(upstream)) {
  if (process.argv.includes("--allow-missing-upstream")) {
    console.log(`upstream checkout not found at ${upstream}; skipping`);
    process.exit(0);
  }
  fail(`upstream checkout not found at ${upstream}`);
}

function gitDescribe() {
  try {
    const commit = execFileSync("git", ["-C", upstream, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
    let tag = "";
    try {
      tag = execFileSync("git", ["-C", upstream, "describe", "--tags", "--exact-match"], { encoding: "utf8" }).trim();
    } catch {
      tag = "";
    }
    return { commit, tag };
  } catch {
    return { commit: "unknown", tag: "" };
  }
}

function readHookNames() {
  const source = fs.readFileSync(path.join(upstream, "src", "plugins", "hook-types.ts"), "utf8");
  const match = source.match(/const PLUGIN_HOOK_NAMES = \[([\s\S]*?)\] as const/);
  if (!match) fail("PLUGIN_HOOK_NAMES not found in src/plugins/hook-types.ts");
  return [...match[1].matchAll(/"([a-z_]+)"/g)].map((entry) => entry[1]);
}

function readSkillCorpus() {
  const entries = [];
  for (const root of ["skills", "custodian-skills"]) {
    const dir = path.join(upstream, root);
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir).sort()) {
      const file = path.join(dir, name, "SKILL.md");
      if (!fs.existsSync(file)) continue;
      const raw = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
      const lines = raw.split("\n");
      const kept = [];
      let inFrontmatter = lines[0]?.trim() === "---";
      let closed = !inFrontmatter;
      for (let index = 0; index < lines.length; index += 1) {
        const line = lines[index];
        kept.push(line);
        if (index > 0 && inFrontmatter && /^---\s*$/.test(line)) {
          inFrontmatter = false;
          closed = true;
          continue;
        }
        if (closed && /^# /.test(line)) break;
      }
      entries.push({ path: `${root}/${name}/SKILL.md`, contents: kept.join("\n") + "\n" });
    }
  }
  return entries;
}

function swiftString(value) {
  let hashes = "#";
  while (value.includes(`"${hashes}`)) hashes += "#";
  return `${hashes}"""\n${value}"""${hashes}`;
}

const { commit, tag } = gitDescribe();
const hookNames = readHookNames();
const corpus = readSkillCorpus();

const out = [];
out.push("// Generated by Scripts/sync-upstream-runtime-ext-fixtures.mjs. Do not edit by hand.");
out.push(`// Upstream: ${tag || "untagged"} (${commit})`);
out.push("");
out.push("/// Upstream fixtures for the runtime extension parity tests (skills, hooks).");
out.push("enum UpstreamRuntimeExtFixtures {");
out.push(`    /// Upstream tag the fixtures were generated from.`);
out.push(`    static let upstreamTag = ${JSON.stringify(tag)}`);
out.push(`    /// Upstream commit the fixtures were generated from.`);
out.push(`    static let upstreamCommit = ${JSON.stringify(commit)}`);
out.push("");
out.push("    /// `PLUGIN_HOOK_NAMES` in upstream declaration order.");
out.push("    static let hookNames: [String] = [");
for (const name of hookNames) out.push(`        ${JSON.stringify(name)},`);
out.push("    ]");
out.push("");
out.push("    /// SKILL.md corpus (frontmatter plus the body up to the first H1), keyed by upstream path.");
out.push("    static let skillCorpus: [(path: String, contents: String)] = [");
for (const entry of corpus) {
  out.push(`        (${JSON.stringify(entry.path)}, ${swiftString(entry.contents)}),`);
}
out.push("    ]");
out.push("}");
out.push("");
const generated = out.join("\n");

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) fail(`${path.relative(repoRoot, outputPath)} is stale; run the script to regenerate it`);
  console.log("runtime extension fixtures are up to date");
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`wrote ${path.relative(repoRoot, outputPath)} (${hookNames.length} hook names, ${corpus.length} skills)`);
}
