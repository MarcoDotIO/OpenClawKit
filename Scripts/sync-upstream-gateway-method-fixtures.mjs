#!/usr/bin/env node
// Generates Tests/OpenClawLinuxRuntimeTests/UpstreamGatewayMethodFixtures.swift from the pinned
// upstream OpenClaw checkout (no network). The fixture is an independent extraction of the gateway
// method table and event list, used to check the generated GatewayMethodCatalog and the in-process
// GatewayServer dispatch table against upstream.
//
// Covered: src/gateway/methods/core-descriptors.ts CORE_GATEWAY_METHOD_SPECS (name, family, scope,
// since, advertise, startup, controlPlaneWrite) and src/gateway/server-methods-list.ts GATEWAY_EVENTS
// (constants resolved from src/gateway/events.ts).
//
// Usage:
//   node Scripts/sync-upstream-gateway-method-fixtures.mjs          # write the fixture file
//   node Scripts/sync-upstream-gateway-method-fixtures.mjs --check  # fail when the file is stale
// Environment: OPENCLAW_UPSTREAM_DIR (default: .codex/openclaw next to this repo).

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.resolve(process.env.OPENCLAW_UPSTREAM_DIR ?? path.join(repoRoot, ".codex", "openclaw"));
const outputPath = path.join(repoRoot, "Tests", "OpenClawLinuxRuntimeTests", "UpstreamGatewayMethodFixtures.swift");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`sync-upstream-gateway-method-fixtures: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(upstream)) {
  if (process.argv.includes("--allow-missing-upstream")) {
    console.log(`upstream checkout not found at ${upstream}; skipping`);
    process.exit(0);
  }
  fail(`upstream checkout not found at ${upstream}`);
}

function gitDescribe() {
  try {
    const commit = execFileSync("git", ["-C", upstream, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
    let tag = "";
    try {
      tag = execFileSync("git", ["-C", upstream, "describe", "--tags", "--exact-match"], { encoding: "utf8" }).trim();
    } catch {
      tag = "";
    }
    return { commit, tag };
  } catch {
    return { commit: "unknown", tag: "" };
  }
}

function readMethodSpecs() {
  const source = fs.readFileSync(path.join(upstream, "src", "gateway", "methods", "core-descriptors.ts"), "utf8");
  const match = source.match(/export const CORE_GATEWAY_METHOD_SPECS = \[([\s\S]*?)\n\] as const/);
  if (!match) fail("CORE_GATEWAY_METHOD_SPECS not found in src/gateway/methods/core-descriptors.ts");
  const constants = {};
  for (const constant of source.matchAll(/const ([A-Z_]+) = (\{[^}]*\}) as const;/g)) {
    constants[constant[1]] = constant[2];
  }
  let body = match[1]
    .split("\n")
    .filter((line) => !line.trim().startsWith("//"))
    .join("\n");
  for (const [name, value] of Object.entries(constants)) {
    body = body.replaceAll(name, value);
  }
  body = body.replace(/([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:/g, '$1"$2":');
  let rows;
  try {
    rows = JSON.parse(`[${body}]`.replace(/,(\s*[\]}])/g, "$1"));
  } catch (error) {
    fail(`could not parse CORE_GATEWAY_METHOD_SPECS: ${error.message}`);
  }
  return rows.map(([name, family, scope, since, policy = {}]) => ({
    name,
    family,
    scope,
    since,
    advertised: policy.advertise !== false,
    startupGated: policy.startup === true,
    controlPlaneWrite: policy.controlPlaneWrite === true,
  }));
}

function readEventNames() {
  const events = fs.readFileSync(path.join(upstream, "src", "gateway", "events.ts"), "utf8");
  const constants = {};
  for (const constant of events.matchAll(/export const (GATEWAY_EVENT_[A-Z_]+) = "([^"]+)"/g)) {
    constants[constant[1]] = constant[2];
  }
  const source = fs.readFileSync(path.join(upstream, "src", "gateway", "server-methods-list.ts"), "utf8");
  const match = source.match(/export const GATEWAY_EVENTS = \[([\s\S]*?)\];/);
  if (!match) fail("GATEWAY_EVENTS not found in src/gateway/server-methods-list.ts");
  return match[1]
    .split("\n")
    .map((line) => line.trim().replace(/,$/, ""))
    .filter((line) => line && !line.startsWith("//"))
    .map((token) => {
      if (token.startsWith('"')) return JSON.parse(token);
      if (constants[token]) return constants[token];
      fail(`unknown event constant ${token}`);
      return token;
    });
}

function swiftString(value) {
  return JSON.stringify(value);
}

function render() {
  const { commit, tag } = gitDescribe();
  const specs = readMethodSpecs();
  const events = readEventNames();
  const lines = [];
  lines.push("// Generated by Scripts/sync-upstream-gateway-method-fixtures.mjs. Do not edit by hand.");
  lines.push(`// Upstream: ${tag || "untagged"} (${commit})`);
  lines.push("// swiftlint:disable line_length");
  lines.push("");
  lines.push("/// Upstream fixtures for the gateway method-table parity tests.");
  lines.push("enum UpstreamGatewayMethodFixtures {");
  lines.push("    /// One `CORE_GATEWAY_METHOD_SPECS` row.");
  lines.push("    struct Spec: Sendable, Equatable {");
  lines.push("        let name: String");
  lines.push("        let family: String?");
  lines.push("        let scope: String");
  lines.push("        let since: String");
  lines.push("        let advertised: Bool");
  lines.push("        let startupGated: Bool");
  lines.push("        let controlPlaneWrite: Bool");
  lines.push("    }");
  lines.push("");
  lines.push("    /// Upstream tag the fixtures were generated from.");
  lines.push(`    static let upstreamTag = ${swiftString(tag)}`);
  lines.push("    /// Upstream commit the fixtures were generated from.");
  lines.push(`    static let upstreamCommit = ${swiftString(commit)}`);
  lines.push("");
  lines.push("    /// `CORE_GATEWAY_METHOD_SPECS` in upstream table order.");
  lines.push("    static let methods: [Spec] = [");
  for (const spec of specs) {
    lines.push(
      `        Spec(name: ${swiftString(spec.name)}, family: ${spec.family === null ? "nil" : swiftString(spec.family)}, scope: ${swiftString(spec.scope)}, since: ${swiftString(spec.since)}, advertised: ${spec.advertised}, startupGated: ${spec.startupGated}, controlPlaneWrite: ${spec.controlPlaneWrite}),`,
    );
  }
  lines.push("    ]");
  lines.push("");
  lines.push("    /// `GATEWAY_EVENTS` in upstream order.");
  lines.push("    static let events: [String] = [");
  for (const event of events) {
    lines.push(`        ${swiftString(event)},`);
  }
  lines.push("    ]");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

const rendered = render();
if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== rendered) fail(`${path.relative(repoRoot, outputPath)} is stale; run node Scripts/sync-upstream-gateway-method-fixtures.mjs`);
  console.log("gateway method fixtures are up to date");
} else {
  fs.writeFileSync(outputPath, rendered);
  console.log(`wrote ${path.relative(repoRoot, outputPath)}`);
}
