#!/usr/bin/env node
// Generates the upstream core tool catalog parity fixture for OpenClawLinuxRuntimeTests.
//
// Reads the pinned upstream checkout (no network), evaluates the pure-data
// CORE_TOOL_SECTION_ORDER / CORE_TOOL_DEFINITIONS literals from
// src/agents/tool-catalog.ts (description presets resolved from
// src/agents/tool-description-presets.ts), and writes
// Tests/OpenClawLinuxRuntimeTests/UpstreamToolCatalogFixture.swift.
//
// Usage: node Scripts/sync-upstream-tool-catalog-fixture.mjs [--check]
// Env:   OPENCLAW_UPSTREAM_DIR (default: .codex/openclaw)

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.resolve(root, process.env.OPENCLAW_UPSTREAM_DIR ?? ".codex/openclaw");
const output = path.join(root, "Tests/OpenClawLinuxRuntimeTests/UpstreamToolCatalogFixture.swift");
const check = process.argv.includes("--check");

function read(relative) {
  return fs.readFileSync(path.join(upstream, relative), "utf8");
}

function upstreamCommit() {
  try {
    return execFileSync("git", ["-C", upstream, "rev-parse", "--short=10", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

function extractLiteral(source, name) {
  const start = source.indexOf(`const ${name}`);
  if (start < 0) throw new Error(`missing ${name}`);
  const equals = source.indexOf("=", start);
  const open = source.indexOf("[", equals);
  let depth = 0;
  for (let index = open; index < source.length; index += 1) {
    const char = source[index];
    if (char === "[" || char === "{") depth += 1;
    if (char === "]" || char === "}") depth -= 1;
    if (depth === 0) return source.slice(open, index + 1);
  }
  throw new Error(`unterminated ${name}`);
}

const presetsSource = read("src/agents/tool-description-presets.ts");
const presets = {};
for (const match of presetsSource.matchAll(/export const ([A-Z0-9_]+)\s*=\s*\n?\s*(["'])((?:\\.|(?!\2).)*)\2;/gs)) {
  presets[match[1]] = match[3];
}
const automationsSource = read("src/agents/tools/automations-tool-name.ts");
const automationsName = /AUTOMATIONS_TOOL_NAME\s*=\s*"([^"]+)"/.exec(automationsSource)?.[1] ?? "automations";

const catalogSource = read("src/agents/tool-catalog.ts");
const scope = { ...presets, AUTOMATIONS_TOOL_NAME: automationsName };
const evaluate = (literal) =>
  new Function(...Object.keys(scope), `return (${literal});`)(...Object.values(scope));
const sections = evaluate(extractLiteral(catalogSource, "CORE_TOOL_SECTION_ORDER"));
const tools = evaluate(extractLiteral(catalogSource, "CORE_TOOL_DEFINITIONS")).map((tool) => ({
  id: tool.id,
  section: tool.sectionId,
  profiles: tool.profiles,
  openclawGroup: tool.includeInOpenClawGroup === true,
}));

const lines = (items) => items.map((item) => `    ${JSON.stringify(item)}`).join(",\n");
const fixture = `{
  "commit": ${JSON.stringify(upstreamCommit())},
  "sections": [
${lines(sections)}
  ],
  "tools": [
${lines(tools)}
  ]
}`;
const swift = `// Generated by Scripts/sync-upstream-tool-catalog-fixture.mjs. Do not edit.
// Source: OpenClaw src/agents/tool-catalog.ts at ${upstreamCommit()}.

enum UpstreamToolCatalogFixture {
    static let json = #"""
${fixture}
"""#
}
`;

if (check) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
  if (current !== swift) {
    console.error(`${path.relative(root, output)} is stale; run node Scripts/sync-upstream-tool-catalog-fixture.mjs`);
    process.exit(1);
  }
  console.log("tool catalog fixture is up to date");
} else {
  fs.writeFileSync(output, swift);
  console.log(`wrote ${path.relative(root, output)} (${tools.length} tools, ${sections.length} sections)`);
}
